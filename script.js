(function () {
    const waBtn = document.getElementById('wa-float-btn');

    // En contacto.html hay un botón inline junto al teléfono; ocultar el flotante
    if (waBtn && document.getElementById('wa-phone-wrapper')) {
        waBtn.style.display = 'none';
        return;
    }

    function updateWaBtnPosition() {
        const navbar = document.querySelector('.navbar');
        if (!navbar || !waBtn) return;
        const navBottom = navbar.getBoundingClientRect().bottom;
        waBtn.style.top = (navBottom + 12) + 'px';
    }

    if (waBtn) {
        updateWaBtnPosition();
        window.addEventListener('scroll', updateWaBtnPosition);
        window.addEventListener('resize', updateWaBtnPosition);
    }
})();
