// Snapshot del HTML español original (se rellena en DOMContentLoaded antes de cualquier cambio)
let _snapshotES = null;

document.addEventListener('DOMContentLoaded', () => {

    // Mobile Menu
    const mobileToggle = document.querySelector('.mobile-toggle');
    const navLinks = document.querySelector('.nav-links');
    if (mobileToggle) {
        mobileToggle.addEventListener('click', () => {
            navLinks.classList.toggle('active');
            mobileToggle.textContent = navLinks.classList.contains('active') ? '✕' : '☰';
            // Cerrar dropdowns al cerrar el menú
            if (!navLinks.classList.contains('active')) {
                document.querySelectorAll('.dropdown-container.open')
                    .forEach(c => c.classList.remove('open'));
            }
        });
    }

    // Dropdown móvil — toggle al pulsar el enlace de "Ubicación"
    document.querySelectorAll('.dropdown-container > a').forEach(link => {
        link.addEventListener('click', e => {
            if (window.innerWidth <= 1024) {
                e.preventDefault();
                const container = link.closest('.dropdown-container');
                const isOpen = container.classList.contains('open');
                // Cerrar todos los demás dropdowns abiertos
                document.querySelectorAll('.dropdown-container.open')
                    .forEach(c => c.classList.remove('open'));
                if (!isOpen) container.classList.add('open');
            }
        });
    });

    // Language Toggle Logic
    const langOpts = document.querySelectorAll('.lang-opt');

    // Load saved language preference on page load
    const savedLang = localStorage.getItem('preferred-language') || 'es';

    // Apply saved language
    langOpts.forEach(opt => {
        if (opt.dataset.lang === savedLang) {
            opt.classList.add('active');
        } else {
            opt.classList.remove('active');
        }
    });

    // Capturar HTML español original antes de cualquier cambio de idioma
    _snapshotES = { ids: {}, dataTr: [], placeholders: {} };
    TRANSLATABLE_IDS.forEach(id => {
        const el = document.getElementById(id);
        if (el) _snapshotES.ids[id] = el.innerHTML;
    });
    document.querySelectorAll('[data-tr]').forEach(el => {
        _snapshotES.dataTr.push({ el, html: el.innerHTML });
    });
    ['input-name', 'input-surname', 'input-age', 'input-country', 'input-uni', 'input-comments'].forEach(id => {
        const el = document.getElementById(id);
        if (el) _snapshotES.placeholders[id] = el.placeholder;
    });

    // Apply translations immediately
    if (savedLang !== 'es') {
        changeLanguage(savedLang);
    }

    langOpts.forEach(opt => {
        opt.addEventListener('click', () => {
            langOpts.forEach(o => o.classList.remove('active'));
            opt.classList.add('active');

            const lang = opt.dataset.lang;
            // Save language preference
            localStorage.setItem('preferred-language', lang);
            changeLanguage(lang);
        });
    });

});

function changeLanguage(lang) {
    // Restaurar español original desde el snapshot (nunca retrotraducir)
    if (lang === 'es' && _snapshotES) {
        TRANSLATABLE_IDS.forEach(id => {
            const el = document.getElementById(id);
            if (el && _snapshotES.ids[id] !== undefined) el.innerHTML = _snapshotES.ids[id];
        });
        _snapshotES.dataTr.forEach(({ el, html }) => { el.innerHTML = html; });
        Object.entries(_snapshotES.placeholders).forEach(([id, txt]) => updatePlaceholder(id, txt));
        return;
    }

    const t = translations[lang];
    if (!t) return;

    // Helper to convert kebab-case ID to camelCase translation key
    const toCamel = (s) => s.replace(/-([a-z0-9])/g, (g) => g[1].toUpperCase());

    TRANSLATABLE_IDS.forEach(id => {
        const el = document.getElementById(id);
        if (el && t[toCamel(id)]) {
            el.innerHTML = t[toCamel(id)];
        }
    });

    // Elements translated via data-tr attribute (shared keys, multiple elements)
    document.querySelectorAll('[data-tr]').forEach(el => {
        const key = el.dataset.tr;
        if (t[key]) el.innerHTML = t[key];
    });

    // Placeholder Updates
    updatePlaceholder('input-name', t.phName);
    updatePlaceholder('input-surname', t.phSurname);
    updatePlaceholder('input-age', t.phAge);
    updatePlaceholder('input-country', t.phCountry);
    updatePlaceholder('input-uni', t.phUni);
    updatePlaceholder('input-comments', t.phComments);

    // Explicit top bar (has HTML)
    setHtml('top-bar-text', t.topBar);
}

function setHtml(id, html) {
    const el = document.getElementById(id);
    if (el) el.innerHTML = html;
}

function updatePlaceholder(id, txt) {
    const el = document.getElementById(id);
    if (el) el.placeholder = txt;
}

